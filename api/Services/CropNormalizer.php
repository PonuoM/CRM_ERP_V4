    /**
     * ล้างข้อความให้อยู่ในรูปมาตรฐาน — ใช้เป็น name_norm สำหรับกันซ้ำที่ระดับ DB ด้วย
     * แก้ typo เชิงระบบที่พบบ่อยในข้อมูลจริง:
     *   "เเ" (สระเอ 2 ตัว) -> "แ"      พบ 3,822 แถวที่จริงคือ "ทุเรียน" แต่ถูกนับแยก
     *   " ํา" -> "ำ"                    (นิคหิต+สระอา แทนที่จะเป็นสระอำ)
     *   สระ/วรรณยุกต์ซ้ำติดกัน          "ทุุเรียน" -> "ทุเรียน"
     */
    public static function clean($s)
    {
        if ($s === null) return '';
        $s = (string)$s;
        $s = preg_replace('/[\x{200B}-\x{200D}\x{FEFF}\x{00A0}]/u', ' ', $s);
        $s = str_replace(array("\t", "\r", "\n", "\0"), ' ', $s);
        $s = str_replace(array('เเ', "\xE0\xB9\x8D\xE0\xB8\xB2"), array('แ', 'ำ'), $s);
        $s = preg_replace('/([\x{0E31}\x{0E34}-\x{0E3A}\x{0E47}-\x{0E4E}])\1+/u', '$1', $s);
        $s = preg_replace('/\s+/u', ' ', $s);
        return trim($s);
    }

    public static function isJunk($s)
    {
        $s = trim($s);
        if ($s === '') return true;
        if (in_array($s, self::$JUNK_EXACT, true)) return true;
        if (in_array($s, self::$NON_CROP, true)) return true;
        if (preg_match('/^[\-\_\.\,\/\+\*\?\s0]+$/u', $s)) return true;
        return false;
    }

    private static function strip($s)
    {
        foreach (self::$STRIP_PATTERNS as $p) { $s = preg_replace($p, ' ', $s); }
        $s = preg_replace('/\s+/u', ' ', $s);
        return trim($s, " \t\n\r\0\x0B-_.,/+*");
    }

    private static function sortedNames()
    {
        if (self::$sortedNames === null) {
            $names = array_keys(array_merge(self::$CANON, self::$ALIAS));
            usort($names, array(__CLASS__, 'cmpByLenDesc'));
            self::$sortedNames = $names;
        }
        return self::$sortedNames;
    }
    /**
     * เรียงยาวก่อน (กัน "มะพร้าวน้ำหอม" โดนจับเป็น "มะพร้าว")
     * ถ้ายาวเท่ากันให้เรียงตามชื่อ — ต้องมี tie-break ที่แน่นอน ไม่งั้นผลลัพธ์ไม่นิ่ง
     * (usort ของ PHP ก่อน 8.0 ไม่ stable: "ทุเรียน" กับ "มะพร้าว" ยาว 7 เท่ากัน ใครชนะก็เปลี่ยนไปมา)
     */
    public static function cmpByLenDesc($a, $b)
    {
        $d = mb_strlen($b, 'UTF-8') - mb_strlen($a, 'UTF-8');
        return ($d !== 0) ? $d : strcmp($a, $b);
    }

    private static function toCanon($name)
    {
        return isset(self::$ALIAS[$name]) ? self::$ALIAS[$name] : $name;
    }

    /**
     * แปลงข้อความชิ้นเดียวเป็นชื่อพืชมาตรฐาน
     * $loose = false : เทียบตรงตัว / alias / ลอกคำขยาย เท่านั้น
     * $loose = true  : เปิด substring match (ยาวสุดก่อน) เป็นทางเลือกสุดท้าย
     */
    public static function mapOne($tok, $loose = true)
    {
        $tok = trim($tok);
        if ($tok === '') return null;
        if (isset(self::$CANON[$tok])) return $tok;
        if (isset(self::$ALIAS[$tok])) return self::$ALIAS[$tok];

        $s = self::strip($tok);
        if ($s !== '' && isset(self::$CANON[$s])) return $s;
        if ($s !== '' && isset(self::$ALIAS[$s])) return self::$ALIAS[$s];
        if (!$loose) return null;

        foreach (self::sortedNames() as $name) {
            if (mb_strlen($name, 'UTF-8') < 3) continue;   // สั้นเกินไป เสี่ยงจับมั่ว
            if (mb_strpos($tok, $name, 0, 'UTF-8') !== false
                || ($s !== '' && mb_strpos($s, $name, 0, 'UTF-8') !== false)) {
                return self::toCanon($name);
            }
        }
        return null;
    }

    /** กวาดหาชื่อพืชทุกตัวที่ฝังอยู่ในข้อความ (ยาวสุดก่อน แล้วตัดออกไม่ให้ซ้อน) */
    public static function scanAll($s)
    {
        $work = $s;
        $found = array();
        foreach (self::sortedNames() as $name) {
            if (mb_strlen($name, 'UTF-8') < 3) continue;
            while (($pos = mb_strpos($work, $name, 0, 'UTF-8')) !== false) {
                $found[self::toCanon($name)] = true;
                $work = mb_substr($work, 0, $pos, 'UTF-8') . ' '
                      . mb_substr($work, $pos + mb_strlen($name, 'UTF-8'), null, 'UTF-8');
            }
        }
        return array_keys($found);
    }

    /**
     * แตกข้อความ "พืชพันธุ์" -> รายชื่อพืชมาตรฐาน (ได้หลายตัว = ลูกค้ามีหลายแปลง)
     *
     * ลำดับสำคัญมาก: ต้องลองแตกหลายพืชก่อน substring match
     * ไม่งั้น "ทุเรียน เงาะ" จะถูกกลืนเหลือแค่ "ทุเรียน" (บั๊กที่เจอตอนทดสอบรอบแรก)
     *
     * คืน array('status'=>..., 'crops'=>array(...))
     *   exact | split | split_partial | split_space | scan_multi | scan_one | junk | unmatched
     */
    public static function parseCrops($raw)
    {
        $s = self::clean($raw);
        if (self::isJunk($s)) return array('status' => 'junk', 'crops' => array());

        // 1) ทั้งก้อนตรงตัว/alias (ยังไม่เปิด substring)
        $one = self::mapOne($s, false);
        if ($one !== null) return array('status' => 'exact', 'crops' => array($one));

        // 2) แตกด้วยตัวคั่นชัดเจน
        //    แต่ละชิ้นใช้ scanAll ไม่ใช่ mapOne เพราะชิ้นเดียวอาจมีหลายพืชซ้อนอยู่
        //    เช่น "ทุเรียน มะพร้าว และอื่นๆ" -> ชิ้นแรกคือ "ทุเรียน มะพร้าว" ต้องได้ทั้งคู่
        //    (mapOne คืนได้ตัวเดียว ทำให้พืชที่สองหายไปเงียบๆ)
        $parts = preg_split('/\s*(?:\/\/|\/|,|\+|&|และ|กับ|\||;)\s*/u', $s, -1, PREG_SPLIT_NO_EMPTY);
        if (count($parts) > 1) {
            $out = array(); $miss = 0;
            foreach ($parts as $p) {
                $found = self::scanAll(self::strip($p));
                if (count($found) === 0) {
                    $m = self::mapOne($p, true);
                    if ($m !== null) $found = array($m);
                }
                if (count($found) > 0) {
                    foreach ($found as $f) { $out[$f] = true; }
                } else {
                    $miss++;
                }
            }
            if (count($out) > 0) {
                return array('status' => ($miss ? 'split_partial' : 'split'), 'crops' => array_keys($out));
            }
        }

        // 3) แตกด้วยช่องว่าง — เฉพาะเมื่อทุกชิ้นรู้จักแบบเข้ม (กัน "ผักสวนครัว" โดนหั่นเป็น ผัก+สวนครัว)
        $sp = preg_split('/\s+/u', $s, -1, PREG_SPLIT_NO_EMPTY);
        if (count($sp) > 1) {
            $out = array(); $ok = true;
            foreach ($sp as $p) {
                $m = self::mapOne($p, false);
                if ($m === null) { $ok = false; break; }
                $out[$m] = true;
            }
            if ($ok && count($out) > 0) return array('status' => 'split_space', 'crops' => array_keys($out));
        }

        // 4) กวาดหาชื่อพืชที่ฝังในข้อความ (จับหลายพืชที่ไม่มีตัวคั่นชัด)
        $scan = self::scanAll($s);
        if (count($scan) > 1) return array('status' => 'scan_multi', 'crops' => $scan);
        if (count($scan) === 1) return array('status' => 'scan_one', 'crops' => $scan);

        return array('status' => 'unmatched', 'crops' => array());
    }

