-- 092 — เลือกได้ว่าจะโทรเบอร์หลักหรือเบอร์สำรองตัวไหน
--
-- ลูกค้าหลายรายมีเบอร์สำรอง (customers.backup_phone เก็บหลายเบอร์คั่นจุลภาค) เทเลต้องเลือกได้
-- ว่าจะโทรเบอร์ไหน โดยที่ยังไม่เห็นเลขจริงสักตัว
--
-- เก็บเป็น "ลำดับที่" ไม่ใช่ตัวเบอร์ — ตั้งใจ เพราะการเก็บเบอร์ซ้ำลงตารางนี้เท่ากับสร้างสำเนา
-- ข้อมูลส่วนบุคคลเพิ่มอีกที่หนึ่งโดยไม่จำเป็น ตอนมือถือมารับงานค่อยไปอ่านจาก customers สด ๆ
--
--   0 = customers.phone (เบอร์หลัก)
--   1..n = ลำดับที่ n ใน customers.backup_phone

ALTER TABLE `call_sessions`
    ADD COLUMN IF NOT EXISTS `phone_index` TINYINT UNSIGNED NOT NULL DEFAULT 0
        COMMENT '0 = เบอร์หลัก, 1..n = เบอร์สำรองลำดับที่ n' AFTER `customer_id`;
