-- 094 — กันบิลเบิ้ล: กุญแจประจำใบจากฝั่งหน้าจอ (idempotency key)
--
-- ปัญหา: หน้าเปิดบิลขอเลขบิลใหม่ทุกครั้งที่กดปุ่ม (GET orders/sequence) เลข id จึงไม่มีวันซ้ำ
-- PRIMARY KEY บน orders.id เลยไม่เคยกันอะไรได้เลย พอเซิร์ฟเวอร์ commit บิลสำเร็จแล้วแต่ตอบกลับ
-- ไม่ทัน/ไม่ครบ หน้าจอจะขึ้นว่า "บันทึกไม่สำเร็จ กรุณาลองใหม่" ทั้งที่บิลอยู่ใน DB แล้ว
-- คนกดใหม่ = ได้บิลใบที่สอง (27 ส.ค. 2026 เกิดแบบนี้ 63 คู่ใน 4 ชั่วโมง)
--
-- ทางแก้: ให้ "ความตั้งใจเปิดบิลหนึ่งครั้ง" มี UUID ของตัวเองที่ไม่เปลี่ยนตอนกดซ้ำ แล้วให้
-- ฐานข้อมูลเป็นคนบังคับว่า UUID หนึ่งตัวมีบิลได้ใบเดียว การกดซ้ำจะชนคีย์ แล้ว API ตอบเลขบิล
-- เดิมกลับไปแทนที่จะสร้างใบใหม่
--
-- ทำไมถึงไม่กระทบลูกค้าที่สั่งของเดิมซ้ำจริง: การเปิดบิลคนละครั้งได้ UUID คนละตัวเสมอ
-- กฎนี้จึงไม่ได้เดาจาก "ยอดเท่ากัน + เวลาใกล้กัน" ซึ่งตัดสินผิดได้
--
-- คอลัมน์เป็น NULL ได้ตั้งใจ: บิลเก่า 394,xxx ใบไม่มีคีย์ และ MariaDB ยอมให้ NULL ซ้ำกันได้
-- ใน UNIQUE index จึงไม่ต้องไปแตะข้อมูลเดิมแม้แต่แถวเดียว
--
-- วิธีรัน:
--   php C:/AppServ/www/voicecall/ops/db.php erp api/migrations/094_order_idempotency.sql
--
-- ⚠️ orders เป็นตารางที่ใหญ่ (ข้อมูล 156 MB + ดัชนี 529 MB) และมีคนใช้งานตลอดเวลา
-- lock_wait_timeout สั้น ๆ ให้ ALTER ยอมแพ้เองแทนที่จะไปขวางคิวทั้งระบบ (บทเรียนจาก 093)
-- และ LOCK=NONE ให้เปิดบิลกันต่อได้ระหว่างสร้างดัชนี
SET SESSION lock_wait_timeout = 5;

-- ─────────────────────────────────────────────────────────────
-- 1. คอลัมน์เก็บกุญแจ — ต่อท้ายตาราง จึงเป็น INSTANT ไม่ต้องเขียนข้อมูลใหม่
-- ─────────────────────────────────────────────────────────────
ALTER TABLE `orders`
    ADD COLUMN IF NOT EXISTS `client_request_id` CHAR(36) NULL
        COMMENT 'UUID ประจำการเปิดบิลหนึ่งครั้งจากหน้าจอ — กดซ้ำส่งตัวเดิม ใช้กันบิลเบิ้ล';

-- ─────────────────────────────────────────────────────────────
-- 2. คีย์ไม่ซ้ำ — ตัวบังคับกฎจริง
--
-- ถ้าบรรทัดนี้ล้มเพราะ lock_wait_timeout ให้รันซ้ำตอนคนใช้งานน้อย ไม่ต้องแก้อะไร
-- ─────────────────────────────────────────────────────────────
ALTER TABLE `orders`
    ADD UNIQUE INDEX `uq_orders_client_request` (`client_request_id`),
    ALGORITHM = INPLACE, LOCK = NONE;
